// Нормализация SKU: убираем пробелы и ведущие нули.
function normSku(s) {
  return String(s || '').trim().replace(/^0+/, '');
}

router.get(
  '/avito-prices',
  asyncHandler(async (req, res) => {
    if (req.query.token !== SECRET) return res.status(404).json({ error: 'not found' });
    const apply = req.query.apply === '1';

    // Список всех складов из stock_by_store + автоопределение нужного.
    const storesRows = await db.all(
      `SELECT DISTINCT el->>'store' AS store
       FROM products p, jsonb_array_elements(p.stock_by_store) AS el
       WHERE p.stock_by_store IS NOT NULL`,
    );
    const stores = storesRows.map((r) => r.store).filter(Boolean).sort();
    const warehouse = stores.find((s) => /электросталь/i.test(s) && !/уцен/i.test(s)) || null;

    // Все активные продукты с sku.
    const products = await db.all(
      `SELECT id, sku, name FROM products WHERE sku IS NOT NULL AND sku <> '' AND active = TRUE`,
    );
    const bySku = new Map();
    const byNormSku = new Map();
    for (const p of products) {
      bySku.set(String(p.sku).trim(), p);
      byNormSku.set(normSku(p.sku), p);
    }

    const matched = [];
    const unmatched = [];
    for (const row of PRICES) {
      const p = bySku.get(String(row.sku).trim()) || byNormSku.get(normSku(row.sku));
      if (p) matched.push({ sku: row.sku, name: row.name, price: row.price, product_id: p.id, product_name: p.name, product_sku: p.sku });
      else unmatched.push({ sku: row.sku, name: row.name, price: row.price });
    }

    const result = {
      warehouse_used: warehouse,
      warehouses_available: stores,
      total_in_price: PRICES.length,
      matched_count: matched.length,
      unmatched_count: unmatched.length,
      unmatched,
      sample_matched: matched.slice(0, 5),
      applied: false,
    };

    if (apply && warehouse) {
      let upserted = 0;
      for (const m of matched) {
        await db.run(
          `INSERT INTO product_prices (product_id, marketplace, warehouse, price)
           VALUES (?, 'Avito', ?, ?)
           ON CONFLICT (product_id, marketplace, warehouse)
           DO UPDATE SET price = EXCLUDED.price, updated_at = NOW()`,
          m.product_id, warehouse, m.price,
        );
        upserted += 1;
      }
      result.upserted = upserted;
      result.applied = true;
    }
    if (apply && !warehouse) {
      result.error = 'Склад «Электросталь» не найден в stock_by_store';
    }
    res.json(result);
  }),
);

