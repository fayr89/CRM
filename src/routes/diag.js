router.get(
  '/seed-clarifications',
  asyncHandler(async (req, res) => {
    if (req.query.token !== SECRET) return res.status(404).json({ error: 'not found' });

    const admin = await db.get(
      `SELECT id, name FROM users WHERE role = 'admin' AND active = TRUE ORDER BY id LIMIT 1`,
    );
    if (!admin) return res.status(500).json({ error: 'no admin user found' });

    const out = [];
    for (const it of CLARIFICATIONS) {
      const fb = await db.get(
        'SELECT id, user_id, subject, status FROM feedback WHERE id = ?',
        it.feedback_id,
      );
      if (!fb) { out.push({ feedback_id: it.feedback_id, skipped: 'not found' }); continue; }

      // Идемпотентность: не дублируем, если уже есть admin-сообщение длиннее 50 символов.
      const existing = await db.get(
        `SELECT id FROM feedback_messages WHERE feedback_id = ? AND role = 'admin'
         AND length(text) > 50 LIMIT 1`,
        fb.id,
      );
      if (existing) { out.push({ feedback_id: fb.id, skipped: 'already seeded' }); continue; }

      const r = await db.run(
        `INSERT INTO feedback_messages (feedback_id, user_id, user_name, role, text)
         VALUES (?, ?, ?, 'admin', ?) RETURNING id`,
        fb.id, admin.id, admin.name, it.text,
      );

      let statusChanged = false;
      if (it.set_status === 'awaiting_approval' && fb.status !== 'awaiting_approval' && fb.status !== 'closed') {
        await db.run(
          `UPDATE feedback SET status = 'awaiting_approval',
           admin_reply = COALESCE(?, admin_reply),
           resolved_by = ?, resolved_at = NOW(), updated_at = NOW() WHERE id = ?`,
          it.admin_reply || null, admin.id, fb.id,
        );
        statusChanged = true;
      }

      try {
        if (fb.user_id) {
          await notify(
            fb.user_id,
            statusChanged ? 'feedback.awaiting_approval' : 'feedback.message',
            statusChanged
              ? `📮 Подтвердите выполнение: ${fb.subject}`
              : `💬 Вопрос по обращению: ${fb.subject}`,
            it.text.slice(0, 300),
            '#/my-feedback',
          );
        }
      } catch (e) {
        // eslint-disable-next-line no-console
        console.error('[diag clarif] notify:', e.message);
      }
      out.push({ feedback_id: fb.id, message_id: r.lastInsertRowid, status_changed: statusChanged });
    }
    res.json({ ok: true, posted: out });
  }),
);

